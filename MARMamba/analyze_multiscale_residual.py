#!/usr/bin/env python3
"""Analyze whether the Stage-2 residual contains multiple spatial scales.

Inputs are the 16-bit PNG predictions and ground truths already generated by
analyze_stage2_preservation.py.  No model inference or GPU is required.

For residual r = y - b, this script constructs an additive pyramid:
    low_4 = U4(D4(r))
    mid_2 = U2(D2(r)) - low_4
    fine  = r - U2(D2(r))
so that r = low_4 + mid_2 + fine (up to numerical precision).

The components are not orthogonal. Their individual energy ratios therefore
do not have to sum to one; this is reported explicitly in the JSON output.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from PIL import Image
from scipy.ndimage import binary_erosion


IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".tif", ".tiff", ".bmp"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Decompose Stage-2 residuals into scale-4, scale-2, and fine components."
    )
    parser.add_argument("--stage2-dir", required=True, type=Path)
    parser.add_argument("--gt-dir", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument(
        "--gt-threshold",
        type=float,
        default=0.01,
        help="Normalized GT threshold used to form the body mask (default: 0.01).",
    )
    parser.add_argument(
        "--mask-erode",
        type=int,
        default=2,
        help="Body-mask erosion iterations to reduce boundary artifacts (default: 2).",
    )
    parser.add_argument(
        "--significant-energy",
        type=float,
        default=0.05,
        help="Predefined energy-ratio threshold for prevalence reporting (default: 0.05).",
    )
    parser.add_argument("--bootstrap", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=19)
    parser.add_argument(
        "--representative-percentiles",
        type=float,
        nargs="+",
        default=[25.0, 50.0, 75.0],
        help="Percentiles used to select representative multiscale cases.",
    )
    args = parser.parse_args()
    if args.mask_erode < 0:
        parser.error("--mask-erode must be non-negative")
    if not 0.0 < args.significant_energy < 1.0:
        parser.error("--significant-energy must be between 0 and 1")
    if any(p < 0.0 or p > 100.0 for p in args.representative_percentiles):
        parser.error("Representative percentiles must be in [0,100]")
    return args


def index_images(folder: Path) -> dict[str, Path]:
    if not folder.is_dir():
        raise FileNotFoundError(f"Directory does not exist: {folder}")
    result: dict[str, Path] = {}
    for path in sorted(folder.rglob("*")):
        if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES:
            key = path.stem
            if key in result:
                raise ValueError(f"Duplicate sample ID {key!r} in {folder}")
            result[key] = path
    if not result:
        raise RuntimeError(f"No supported images found in {folder}")
    return result


def read_unit_gray(path: Path) -> np.ndarray:
    with Image.open(path) as image:
        if image.mode not in ("1", "L", "I", "I;16", "F"):
            image = image.convert("L")
        array = np.asarray(image).copy()
    array = array.astype(np.float64)
    maximum = float(np.max(array))
    minimum = float(np.min(array))
    if minimum < 0:
        raise ValueError(f"Negative image values are unsupported: {path}")
    if maximum <= 1.0 + 1e-6:
        scale = 1.0
    elif maximum <= 255.0:
        scale = 255.0
    elif maximum <= 65535.0:
        scale = 65535.0
    else:
        raise ValueError(f"Unsupported intensity range in {path}: max={maximum}")
    return np.clip(array / scale, 0.0, 1.0)


def resize_float(array: np.ndarray, shape: tuple[int, int], resample: int) -> np.ndarray:
    image = Image.fromarray(array.astype(np.float32), mode="F")
    resized = image.resize((shape[1], shape[0]), resample=resample)
    return np.asarray(resized, dtype=np.float64)


def low_pass(array: np.ndarray, factor: int) -> np.ndarray:
    """Bilinear analysis/synthesis approximation at 1/factor resolution."""
    height, width = array.shape
    down_shape = (max(1, height // factor), max(1, width // factor))
    down = resize_float(array, down_shape, Image.Resampling.BILINEAR)
    return resize_float(down, (height, width), Image.Resampling.BILINEAR)


def decompose(residual: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, float]:
    low2 = low_pass(residual, 2)
    low4 = low_pass(residual, 4)
    mid2 = low2 - low4
    fine = residual - low2
    reconstruction_error = float(np.max(np.abs(residual - (low4 + mid2 + fine))))
    return low4, mid2, fine, reconstruction_error


def energy(array: np.ndarray, mask: np.ndarray) -> float:
    values = array[mask]
    return float(np.sum(values * values))


def mean_abs(array: np.ndarray, mask: np.ndarray) -> float:
    return float(np.mean(np.abs(array[mask])))


def bootstrap_ci(values: np.ndarray, n: int, rng: np.random.Generator) -> tuple[float, float]:
    if len(values) == 1:
        return float(values[0]), float(values[0])
    means = np.empty(n, dtype=np.float64)
    chunk = 1000
    for start in range(0, n, chunk):
        count = min(chunk, n - start)
        idx = rng.integers(0, len(values), size=(count, len(values)))
        means[start : start + count] = values[idx].mean(axis=1)
    low, high = np.percentile(means, [2.5, 97.5])
    return float(low), float(high)


def summarize(
    rows: list[dict[str, float | str]],
    column: str,
    bootstrap: int,
    rng: np.random.Generator,
) -> dict[str, float | int]:
    values = np.asarray([float(row[column]) for row in rows], dtype=np.float64)
    low, high = bootstrap_ci(values, bootstrap, rng)
    return {
        "n": int(len(values)),
        "mean": float(np.mean(values)),
        "sd": float(np.std(values, ddof=1)) if len(values) > 1 else 0.0,
        "median": float(np.median(values)),
        "q25": float(np.quantile(values, 0.25)),
        "q75": float(np.quantile(values, 0.75)),
        "ci95_low": low,
        "ci95_high": high,
    }


def representative_indices(records: list[dict], percentiles: list[float]) -> list[int]:
    # Balance score is high only if both modeled scales carry non-trivial energy.
    scores = np.asarray(
        [min(float(r["energy_ratio_scale4"]), float(r["energy_ratio_scale2"])) for r in records]
    )
    chosen: list[int] = []
    for percentile in percentiles:
        target = float(np.percentile(scores, percentile))
        order = np.argsort(np.abs(scores - target))
        index = next(int(i) for i in order if int(i) not in chosen)
        chosen.append(index)
    return chosen


def save_decomposition_figure(records: list[dict], path: Path, percentiles: list[float]) -> None:
    chosen_indices = representative_indices(records, percentiles)
    chosen = [records[i] for i in chosen_indices]
    columns = ["Ground truth", "Stage 2", "Residual $r$", "Scale-4 $c_4$", "Scale-2 $c_2$", "Fine $c_f$"]
    fig, axes = plt.subplots(len(chosen), len(columns), figsize=(16, 3.0 * len(chosen)), squeeze=False)
    for col, title in enumerate(columns):
        axes[0, col].set_title(title, fontsize=11)

    residual_images = []
    for record in chosen:
        residual_images.extend([record["residual"], record["scale4"], record["scale2"], record["fine"]])
    limit = max(float(np.percentile(np.abs(x), 99.5)) for x in residual_images)
    limit = max(limit, 1e-8)
    mappable = None
    for row, (record, percentile) in enumerate(zip(chosen, percentiles)):
        panels = [
            record["gt"], record["stage2"], record["residual"],
            record["scale4"], record["scale2"], record["fine"],
        ]
        for col, panel in enumerate(panels):
            ax = axes[row, col]
            if col < 2:
                ax.imshow(panel, cmap="gray", vmin=0.0, vmax=1.0)
            else:
                mappable = ax.imshow(panel, cmap="coolwarm", vmin=-limit, vmax=limit)
            ax.axis("off")
        axes[row, 0].set_ylabel(
            f"P{percentile:g}\n{record['sample_id']}", fontsize=9
        )
    if mappable is not None:
        cbar = fig.colorbar(mappable, ax=axes[:, 2:].ravel().tolist(), fraction=0.018, pad=0.012)
        cbar.set_label("Signed normalized residual / correction")
    fig.suptitle("Representative Stage-2 residual decomposition within the validation set", fontsize=13)
    fig.subplots_adjust(left=0.04, right=0.92, bottom=0.03, top=0.92, wspace=0.03, hspace=0.08)
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def save_energy_figure(rows: list[dict[str, float | str]], path: Path) -> None:
    scale4 = np.asarray([float(r["energy_ratio_scale4"]) for r in rows])
    scale2 = np.asarray([float(r["energy_ratio_scale2"]) for r in rows])
    fine = np.asarray([float(r["energy_ratio_fine"]) for r in rows])
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    axes[0].boxplot(
        [scale4, scale2, fine],
        tick_labels=["Scale 4", "Scale 2", "Fine"],
        showfliers=False,
        patch_artist=True,
        boxprops={"facecolor": "#8db8d8"},
        medianprops={"color": "#c51b32", "linewidth": 1.5},
    )
    axes[0].set_ylabel(r"Component energy / residual energy")
    axes[0].set_title("Energy-ratio distributions")
    axes[0].grid(axis="y", alpha=0.25)

    bins = np.linspace(0.0, max(np.percentile(scale4, 99), np.percentile(scale2, 99), 0.05), 35)
    axes[1].hist(scale4, bins=bins, alpha=0.65, label="Scale 4", color="#377eb8")
    axes[1].hist(scale2, bins=bins, alpha=0.65, label="Scale 2", color="#e41a1c")
    axes[1].set_xlabel(r"Component energy / residual energy")
    axes[1].set_ylabel("Number of images")
    axes[1].set_title("Modeled-scale energy across images")
    axes[1].legend(frameon=False)
    axes[1].grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    stage2_files = index_images(args.stage2_dir)
    gt_files = index_images(args.gt_dir)
    common = sorted(set(stage2_files) & set(gt_files))
    if not common:
        raise RuntimeError("No matching sample IDs between Stage-2 and GT folders")
    if len(common) != len(stage2_files) or len(common) != len(gt_files):
        print(
            f"Warning: using {len(common)} matched samples from "
            f"{len(stage2_files)} Stage-2 and {len(gt_files)} GT images"
        )
    print(f"Matched validation images: {len(common)}")

    rows: list[dict[str, float | str]] = []
    records: list[dict] = []
    max_reconstruction_error = 0.0
    eps = 1e-20
    structure = np.ones((3, 3), dtype=bool)

    for index, key in enumerate(common, start=1):
        stage2 = read_unit_gray(stage2_files[key])
        gt = read_unit_gray(gt_files[key])
        if stage2.shape != gt.shape:
            raise ValueError(f"Shape mismatch for {key}: Stage2={stage2.shape}, GT={gt.shape}")
        mask = gt > args.gt_threshold
        if args.mask_erode:
            eroded = binary_erosion(mask, structure=structure, iterations=args.mask_erode)
            if np.any(eroded):
                mask = eroded
        if not np.any(mask):
            raise ValueError(f"Empty body mask for sample {key}")

        residual = gt - stage2
        scale4, scale2, fine, reconstruction_error = decompose(residual)
        max_reconstruction_error = max(max_reconstruction_error, reconstruction_error)
        total_energy = energy(residual, mask) + eps
        ratio4 = energy(scale4, mask) / total_energy
        ratio2 = energy(scale2, mask) / total_energy
        ratio_fine = energy(fine, mask) / total_energy
        row: dict[str, float | str] = {
            "sample_id": key,
            "body_pixels": float(np.sum(mask)),
            "residual_energy": total_energy,
            "residual_mean_abs": mean_abs(residual, mask),
            "energy_ratio_scale4": ratio4,
            "energy_ratio_scale2": ratio2,
            "energy_ratio_fine": ratio_fine,
            "mean_abs_scale4": mean_abs(scale4, mask),
            "mean_abs_scale2": mean_abs(scale2, mask),
            "mean_abs_fine": mean_abs(fine, mask),
            "energy_ratio_sum": ratio4 + ratio2 + ratio_fine,
            "max_additive_reconstruction_error": reconstruction_error,
        }
        rows.append(row)
        records.append(
            {
                **row,
                "gt": gt,
                "stage2": stage2,
                "residual": np.where(mask, residual, 0.0),
                "scale4": np.where(mask, scale4, 0.0),
                "scale2": np.where(mask, scale2, 0.0),
                "fine": np.where(mask, fine, 0.0),
            }
        )
        if index == 1 or index % 50 == 0 or index == len(common):
            print(f"Processed {index}/{len(common)}")

    csv_path = args.output_dir / "multiscale_residual_per_image.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    rng = np.random.default_rng(args.seed)
    summary = {
        "dataset": {
            "n": len(rows),
            "gt_threshold": args.gt_threshold,
            "mask_erode_iterations": args.mask_erode,
        },
        "decomposition": {
            "definition": {
                "scale4": "U4(D4(r))",
                "scale2": "U2(D2(r)) - U4(D4(r))",
                "fine": "r - U2(D2(r))",
            },
            "note": (
                "Components are additive but non-orthogonal; energy ratios need not sum to one."
            ),
            "maximum_additive_reconstruction_error": max_reconstruction_error,
        },
        "statistics": {
            column: summarize(rows, column, args.bootstrap, rng)
            for column in (
                "energy_ratio_scale4",
                "energy_ratio_scale2",
                "energy_ratio_fine",
                "mean_abs_scale4",
                "mean_abs_scale2",
                "mean_abs_fine",
            )
        },
        "prevalence": {
            "predefined_energy_ratio_threshold": args.significant_energy,
            "scale4_fraction_above_threshold": float(
                np.mean([float(r["energy_ratio_scale4"]) > args.significant_energy for r in rows])
            ),
            "scale2_fraction_above_threshold": float(
                np.mean([float(r["energy_ratio_scale2"]) > args.significant_energy for r in rows])
            ),
            "both_scales_fraction_above_threshold": float(
                np.mean([
                    float(r["energy_ratio_scale4"]) > args.significant_energy
                    and float(r["energy_ratio_scale2"]) > args.significant_energy
                    for r in rows
                ])
            ),
        },
        "figure_selection": {
            "method": "Nearest cases to predefined percentiles of min(scale4_ratio, scale2_ratio)",
            "percentiles": args.representative_percentiles,
        },
    }
    json_path = args.output_dir / "multiscale_residual_summary.json"
    json_path.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")

    save_decomposition_figure(
        records,
        args.output_dir / "multiscale_residual_decomposition.png",
        args.representative_percentiles,
    )
    save_energy_figure(rows, args.output_dir / "multiscale_residual_energy.png")

    print("\n=== MULTISCALE RESIDUAL ANALYSIS ===")
    for column in ("energy_ratio_scale4", "energy_ratio_scale2", "energy_ratio_fine"):
        stats = summary["statistics"][column]
        print(
            f"{column:24s}: mean={stats['mean']:.6f}, median={stats['median']:.6f}, "
            f"95% CI=[{stats['ci95_low']:.6f}, {stats['ci95_high']:.6f}]"
        )
    prevalence = summary["prevalence"]
    print(
        f"Scale 4 ratio > {args.significant_energy:.2f}: "
        f"{prevalence['scale4_fraction_above_threshold']:.3%} of images"
    )
    print(
        f"Scale 2 ratio > {args.significant_energy:.2f}: "
        f"{prevalence['scale2_fraction_above_threshold']:.3%} of images"
    )
    print(
        f"Both modeled scales > {args.significant_energy:.2f}: "
        f"{prevalence['both_scales_fraction_above_threshold']:.3%} of images"
    )
    print(f"Maximum additive reconstruction error: {max_reconstruction_error:.3e}")
    print(f"Saved outputs to: {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
